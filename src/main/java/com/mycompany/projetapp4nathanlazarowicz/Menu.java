    public void initialisation(){
        //Planning
        Planning planning = new Planning("initialisation", "init");
        labelLundiSeance.setText(planning.getNomSeancePlanning("lundi"));
        labelMardiSeance.setText(planning.getNomSeancePlanning("mardi"));
        labelMercrediSeance.setText(planning.getNomSeancePlanning("mercredi"));
        labelJeudiSeance.setText(planning.getNomSeancePlanning("jeudi"));
        labelVendrediSeance.setText(planning.getNomSeancePlanning("vendredi"));
        labelSamediSeance.setText(planning.getNomSeancePlanning("samedi"));
        labelDimancheSeance.setText(planning.getNomSeancePlanning("dimanche"));
        
        //Exercice
        Exercice exercice = new Exercice("init", "initialisation", "initialisation", "initialisation");
        int ligneExercice = exercice.getNombreLigneExercice();
        //tableExercice.addRow(new Object[]{nomExo, typeExo, grpMuscu, muscle});
        for(int i = 0; i < ligneExercice; i++){
            String[] exerciceData = exercice.lectureDonneesExercice(i+1);
            DefaultTableModel model = (DefaultTableModel) tableExercice.getModel();
            model.addRow(new Object[]{exerciceData[0], exerciceData[1], exerciceData[2], exerciceData[3]});
            /*
            tableExercice.getModel().setValueAt(exerciceData[0], i, 0);
            //System.out.println("Exercice " + i + " = " + exerciceData[0]);
            tableExercice.getModel().setValueAt(exerciceData[1], i, 1);
            tableExercice.getModel().setValueAt(exerciceData[2], i, 2);
            tableExercice.getModel().setValueAt(exerciceData[3], i, 3);
            */
        }
        
        //Seance 
        Seance seance = new Seance("init","initialisation","initialisation");
        int ligneSeance = seance.getNombreLigneSeance();
        for(int i = 0; i < ligneSeance; i++){
            String[] seanceData = seance.lectureDonneesSeance(i+1);
            DefaultTableModel model = (DefaultTableModel) tableSeance.getModel();
            model.addRow(new Object[]{
                    seanceData[0], seanceData[1], seanceData[2], seanceData[3],
                    seanceData[4], seanceData[5], seanceData[6], seanceData[7],
                    seanceData[8], seanceData[9], seanceData[10], seanceData[11]
                    });
        }  
        
        //Musculation
        Musculation muscu = new Musculation("init","initialisation","initialisation", "initialisation");
        int ligneMuscu = muscu.getNombreLigneMusculation();
        for(int i = 0; i < ligneMuscu; i++){
            String[] muscuData = muscu.lectureDonneesMusculation(i+1);
            DefaultTableModel model = (DefaultTableModel) tableMusculation.getModel();
            model.addRow(new Object[]{
                    muscuData[0], muscuData[1], muscuData[2], muscuData[3],
                    muscuData[4], muscuData[5] });
        }
    }

