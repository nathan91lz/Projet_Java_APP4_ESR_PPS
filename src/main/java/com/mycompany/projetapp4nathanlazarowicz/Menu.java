    private void bpSupprimerSeanceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bpSupprimerSeanceActionPerformed
        // TODO add your handling code here:
        String recherche = txtRechercheSeance.getText();
        Seance seance = new Seance("init", "", "");
        int ligne = seance.getNombreLigneSeance();

        seance.removeSeance(recherche);
        ligne --;
        for(int i = 0; i <= ligne; i++){
            String[] seanceData = seance.lectureDonneesSeance(i+1);
            for(int c = 0; c <= 11; c++){
                tableSeance.getModel().setValueAt(seanceData[c], i, c);
            }
        }
        DefaultTableModel model = (DefaultTableModel) tableSeance.getModel();
        model.removeRow(ligne);
    }//GEN-LAST:event_bpSupprimerSeanceActionPerformed

